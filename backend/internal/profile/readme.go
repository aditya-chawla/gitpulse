// Package profile keeps a generated block in the user's profile README
// (<login>/<login>) up to date. Only the text between the gitpulse markers
// is ever changed, only public repos are mentioned, and a commit is made only
// when the block's content actually changed.
package profile

import (
	"errors"
	"fmt"
	"math"
	"strings"
	"time"
)

const (
	StartMarker = "<!-- gitpulse:start -->"
	EndMarker   = "<!-- gitpulse:end -->"
)

var ErrNoMarkers = errors.New("the README has no " + StartMarker + " … " + EndMarker + " block")

// ErrBadMarkers: markers out of order or repeated; refuse rather than guess.
var ErrBadMarkers = errors.New("the README's gitpulse markers must appear exactly once each, start before end")

// Current returns the text between the markers.
func Current(readme string) (string, error) {
	s, e, err := find(readme)
	if err != nil {
		return "", err
	}
	return readme[s+len(StartMarker) : e], nil
}

func find(readme string) (start, end int, err error) {
	ns, ne := strings.Count(readme, StartMarker), strings.Count(readme, EndMarker)
	if ns == 0 && ne == 0 {
		return 0, 0, ErrNoMarkers
	}
	start, end = strings.Index(readme, StartMarker), strings.Index(readme, EndMarker)
	if ns != 1 || ne != 1 || end < start {
		return 0, 0, ErrBadMarkers
	}
	return start, end, nil
}

// Replace swaps the content between the markers for block and returns the
// new README. Every byte outside the markers is kept exactly, including the
// line endings around them.
func Replace(readme, block string) (string, error) {
	s, e, err := find(readme)
	if err != nil {
		return "", err
	}
	nl := "\n"
	if strings.Contains(readme, "\r\n") {
		nl = "\r\n"
		block = strings.ReplaceAll(strings.ReplaceAll(block, "\r\n", "\n"), "\n", "\r\n")
	}
	inner := nl + strings.TrimRight(block, "\r\n") + nl
	return readme[:s+len(StartMarker)] + inner + readme[e:], nil
}

// Same reports whether two blocks are equal ignoring surrounding whitespace
// and line-ending style, so a hand re-save in another editor isn't a change.
func Same(a, b string) bool {
	n := func(s string) string { return strings.TrimSpace(strings.ReplaceAll(s, "\r\n", "\n")) }
	return n(a) == n(b)
}

// --- content ---

type Language struct {
	Name  string
	Bytes int64
}

type Project struct {
	Name        string
	URL         string
	Description string
	Stars       int
	PushedAt    time.Time
}

type Article struct {
	Title     string
	URL       string
	Published time.Time
}

type Data struct {
	Languages []Language // public, non-fork repos only
	Projects  []Project  // public only
	Articles  []Article
	FeedError string // shown in the preview, never in the README
}

// escapeMD keeps titles and descriptions from breaking the markdown (or
// injecting links/HTML into the README).
func escapeMD(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	r := strings.NewReplacer(`\`, `\\`, "[", `\[`, "]", `\]`, "<", "&lt;", ">", "&gt;", "|", `\|`, "`", "'", "*", `\*`, "_", `\_`)
	return r.Replace(s)
}

func trimRunes(s string, n int) string {
	if r := []rune(s); len(r) > n {
		return strings.TrimSpace(string(r[:n-1])) + "…"
	}
	return s
}

// Render builds the block. It contains no timestamps, so it only changes
// when the underlying data does.
func Render(d Data) string {
	var b strings.Builder
	if len(d.Languages) > 0 {
		var total int64
		for _, l := range d.Languages {
			total += l.Bytes
		}
		b.WriteString("#### Top languages\n\n")
		var parts []string
		for i, l := range d.Languages {
			if i == 6 {
				break
			}
			pct := float64(l.Bytes) / float64(total) * 100
			if pct < 1 {
				break
			}
			parts = append(parts, fmt.Sprintf("**%s** %d%%", escapeMD(l.Name), int(math.Round(pct))))
		}
		b.WriteString(strings.Join(parts, " · ") + "\n\n")
	}
	if len(d.Projects) > 0 {
		b.WriteString("#### Recently active projects\n\n")
		for _, p := range d.Projects {
			line := fmt.Sprintf("- [%s](%s)", escapeMD(p.Name), p.URL)
			if p.Description != "" {
				line += ": " + escapeMD(trimRunes(p.Description, 100))
			}
			if p.Stars > 0 {
				line += fmt.Sprintf(" ★ %d", p.Stars)
			}
			b.WriteString(line + "\n")
		}
		b.WriteString("\n")
	}
	if len(d.Articles) > 0 {
		b.WriteString("#### Latest articles\n\n")
		for _, a := range d.Articles {
			line := fmt.Sprintf("- [%s](%s)", escapeMD(trimRunes(a.Title, 120)), a.URL)
			if !a.Published.IsZero() {
				line += " · " + a.Published.UTC().Format("Jan 2, 2006")
			}
			b.WriteString(line + "\n")
		}
		b.WriteString("\n")
	}
	b.WriteString("<sub>Generated by gitpulse</sub>")
	return b.String()
}
